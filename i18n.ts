// EN / RU. UI strings live in STR; game data (cards, weeks, lines…) is wrapped with
// localize(), which serves the Russian override from data/ru.ts when RU is on.

export type Lang = 'en' | 'ru';
const KEY = 'burnout.lang';

function initial(): Lang {
  try {
    const s = localStorage.getItem(KEY);
    if (s === 'en' || s === 'ru') return s;
  } catch { /* storage blocked */ }
  return navigator.language?.toLowerCase().startsWith('ru') || navigator.language?.toLowerCase().startsWith('be') ? 'ru' : 'en';
}

let current: Lang = initial();
document.documentElement.lang = current;

export const lang = () => current;
export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
  try { localStorage.setItem(KEY, l); } catch { /* storage blocked */ }
}

const isPlain = (v: unknown): v is Record<string, unknown> => !!v && typeof v === 'object' && !Array.isArray(v);

function merge(en: unknown, ru: unknown): unknown {
  if (ru === undefined) return en;
  if (isPlain(en) && isPlain(ru)) {
    const out: Record<string, unknown> = { ...en };
    for (const k of Object.keys(ru)) out[k] = merge(en[k], ru[k]);
    return out;
  }
  return ru;
}

/** Wrap a data table so every read returns the current language. */
export function localize<T extends object>(en: T, ru: unknown): T {
  return new Proxy(en, {
    get(target, k, recv) {
      const base = Reflect.get(target, k, recv);
      if (current !== 'ru' || typeof k === 'symbol' || typeof base === 'function') return base;
      const over = (ru as Record<string, unknown> | undefined)?.[k];
      return merge(base, over);
    },
  });
}

